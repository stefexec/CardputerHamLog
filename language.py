# Create a lowercase mapping for case-insensitive lookup
_STRINGS_LOWER = {}
for lang, mapping in STRINGS.items():
    _STRINGS_LOWER[lang] = {k.lower(): v for k, v in mapping.items()}

def get_string(lang_code, key):
    # Use lowercase key for lookup
    lower_key = key.lower()

    # First, try to get the string from the requested language
    lang = _STRINGS_LOWER.get(lang_code, _STRINGS_LOWER["en"])
    
    # Fallback to English if the key is not in the current language
    value = lang.get(lower_key)
    if value is None:
        value = _STRINGS_LOWER["en"].get(lower_key)
        
    # If the key is not in English either, return the key itself
    if value is None:
        return key.replace('_', ' ').title()
        
    return value
