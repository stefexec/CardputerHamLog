def get_flag_surface(callsign, flag_sprite_sheet):
    """
    Finds the longest matching prefix, gets the country code, and returns the
    corresponding flag surface from the sprite sheet.
    """
    callsign = callsign.upper()
    
    # Check for a matching prefix, from longest to shortest
    for length in range(min(len(callsign), 4), 0, -1):
        prefix = callsign[:length]
        if prefix in PREFIX_TO_COUNTRY:
            country_code = PREFIX_TO_COUNTRY[prefix]
            if country_code in FLAG_OFFSETS:
                import pygame
                offset = FLAG_OFFSETS[country_code]
                rect = pygame.Rect(0, offset, 16, 16)
                try:
                    return flag_sprite_sheet.subsurface(rect)
                except ValueError:
                    pass
    return None
